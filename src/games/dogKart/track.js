function catmull(p0, p1, p2, p3, t) {
  // centripetal ではなく uniform。制御点が均等に近いので十分なめらか
  const t2 = t * t;
  const t3 = t2 * t;
  return 0.5 * (2 * p1 + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t3);
}

export class Track {
  /** @param {number | number[][]} course コース番号（COURSES の添字）または制御点の配列 */
  constructor(course = 0) {
    const def = Array.isArray(course) ? { name: 'custom', theme: 'meadow', control: course } : COURSES[course] || COURSES[0];
    const control = def.control;
    this.name = def.name;
    this.theme = def.theme;
    this.roadHalf = 11; // 道路の半幅
    this.wallDist = 15.5; // 中心線から壁までの距離（道路の外は芝生）
    this.checkpoints = RACE.CHECKPOINTS;

    // 1. 細かくサンプリング
    const dense = [];
    const n = control.length;
    for (let i = 0; i < n; i++) {
      const p0 = control[(i - 1 + n) % n];
      const p1 = control[i];
      const p2 = control[(i + 1) % n];
      const p3 = control[(i + 2) % n];
      for (let k = 0; k < 40; k++) {
        const t = k / 40;
        dense.push([catmull(p0[0], p1[0], p2[0], p3[0], t), catmull(p0[1], p1[1], p2[1], p3[1], t)]);
      }
    }
    // 2. 弧長で等間隔に並べ直す
    const cum = [0];
    for (let i = 1; i <= dense.length; i++) {
      const a = dense[i - 1];
      const b = dense[i % dense.length];
      cum.push(cum[i - 1] + Math.hypot(b[0] - a[0], b[1] - a[1]));
    }
    const total = cum[dense.length];
    const N = Math.round(total / 2.5);
    this.n = N;
    this.x = new Float64Array(N);
    this.z = new Float64Array(N);
    let j = 0;
    for (let i = 0; i < N; i++) {
      const s = (i / N) * total;
      while (cum[j + 1] < s) j++;
      const a = dense[j];
      const b = dense[(j + 1) % dense.length];
      const t = (s - cum[j]) / (cum[j + 1] - cum[j] || 1);
      this.x[i] = a[0] + (b[0] - a[0]) * t;
      this.z[i] = a[1] + (b[1] - a[1]) * t;
    }
    // 3. 各セグメントの長さ・接線・左向き法線
    this.segLen = new Float64Array(N);
    this.cum = new Float64Array(N + 1);
    this.tx = new Float64Array(N);
    this.tz = new Float64Array(N);
    for (let i = 0; i < N; i++) {
      const k = (i + 1) % N;
      const dx = this.x[k] - this.x[i];
      const dz = this.z[k] - this.z[i];
      const len = Math.hypot(dx, dz) || 1e-6;
      this.segLen[i] = len;
      this.tx[i] = dx / len;
      this.tz[i] = dz / len;
      this.cum[i + 1] = this.cum[i] + len;
    }
    this.length = this.cum[N];
    // ブーストパッド: 1 周に 10 枚（コース上の割合位置と横位置）。アイテムボックスとは重ならない場所
    this.pads = [[0.05, 0], [0.185, -5], [0.215, 5], [0.35, 0], [0.51, -5], [0.54, 5], [0.69, 0], [0.84, -5], [0.87, 5], [0.975, 0]].map(([f, lat]) => {
      const p = this.pointAt(f * this.length, lat);
      return { x: p.x, z: p.z, h: p.h, tx: p.tx, tz: p.tz };
    });
    // トンネル: 弧長 s の範囲に直す
    this.tunnels = (def.tunnels || []).map(([a, b]) => ({ a: a * this.length, b: b * this.length }));
    // ドッグフード: 25 か所に 5 個ずつ（まっすぐ・斜め・ジグザグ）。取られても一定時間でまた出る
    this.foods = [];
    for (let g = 0; g < FOOD.GROUPS; g++) {
      const f = (g + 0.5) / FOOD.GROUPS;
      const pat = g % 4;
      for (let j = 0; j < FOOD.PER_GROUP; j++) {
        const u = j / (FOOD.PER_GROUP - 1); // 0..1
        const lat = pat === 0 ? (g % 8 === 0 ? 0 : -3 + 6 * ((g >> 2) % 2)) : pat === 1 ? -6 + 12 * u : pat === 2 ? 6 - 12 * u : j % 2 ? 5 : -5;
        const p = this.pointAt(f * this.length + (j - (FOOD.PER_GROUP - 1) / 2) * FOOD.SPACING, lat);
        this.foods.push({ x: p.x, z: p.z });
      }
    }
    this._buildGrid();
    this._proj = { i: 0, t: 0, s: 0, lat: 0, cx: 0, cz: 0, tx: 0, tz: 1, nx: 1, nz: 0 };
    this._pcache = new Float64Array(64 * 12).fill(NaN);
  }

  /**
   * 点 (x, z) をコース中心線に投影する。
   * 戻り値は内部で再利用するオブジェクトなので、必要な値はすぐにコピーすること。
   * lat > 0 は進行方向の左側。
   */
  project(x, z) {
    // 同じ位置は 1 ステップの中で何度も調べられる（順位・壁・周回・NPC・アイテム）ので、直近の結果を覚えておく（小さな表）
    const C = this._pcache;
    const slot = (Math.imul((x * 64) | 0, 73856093) ^ Math.imul((z * 64) | 0, 19349663)) & 63;
    const o = slot * 12;
    if (C[o] === x && C[o + 1] === z) {
      const hit = this._proj;
      hit.i = C[o + 2];
      hit.t = C[o + 3];
      hit.s = C[o + 4];
      hit.lat = C[o + 5];
      hit.cx = C[o + 6];
      hit.cz = C[o + 7];
      hit.tx = C[o + 8];
      hit.tz = C[o + 9];
      hit.nx = C[o + 10];
      hit.nz = C[o + 11];
      return hit;
    }
    const r = this._project(x, z);
    C[o] = x;
    C[o + 1] = z;
    C[o + 2] = r.i;
    C[o + 3] = r.t;
    C[o + 4] = r.s;
    C[o + 5] = r.lat;
    C[o + 6] = r.cx;
    C[o + 7] = r.cz;
    C[o + 8] = r.tx;
    C[o + 9] = r.tz;
    C[o + 10] = r.nx;
    C[o + 11] = r.nz;
    return r;
  }

  _project(x, z) {
    const N = this.n;
    let best = Infinity;
    let bi = 0;
    let bt = 0;
    // 近くのセグメントだけ調べる（格子）。近くに見つからないときだけ全部調べる
    const G = this._grid;
    const gx = Math.floor((x - G.x0) / G.cell);
    const gz = Math.floor((z - G.z0) / G.cell);
    let list = null;
    if (gx >= 0 && gz >= 0 && gx < G.nx && gz < G.nz) list = G.cells[gz * G.nx + gx];
    if (list) {
      for (let k = 0; k < list.length; k++) {
        const i = list[k];
        const ax = this.x[i];
        const az = this.z[i];
        const dx = x - ax;
        const dz = z - az;
        let t = (dx * this.tx[i] + dz * this.tz[i]) / this.segLen[i];
        t = t < 0 ? 0 : t > 1 ? 1 : t;
        const qx = ax + this.tx[i] * this.segLen[i] * t;
        const qz = az + this.tz[i] * this.segLen[i] * t;
        const d = (x - qx) * (x - qx) + (z - qz) * (z - qz);
        if (d < best) {
          best = d;
          bi = i;
          bt = t;
        }
      }
    }
    if (best > G.reach * G.reach) {
      best = Infinity;
      for (let i = 0; i < N; i++) {
        const ax = this.x[i];
        const az = this.z[i];
        const dx = x - ax;
        const dz = z - az;
        let t = (dx * this.tx[i] + dz * this.tz[i]) / this.segLen[i];
        t = t < 0 ? 0 : t > 1 ? 1 : t;
        const qx = ax + this.tx[i] * this.segLen[i] * t;
        const qz = az + this.tz[i] * this.segLen[i] * t;
        const d = (x - qx) * (x - qx) + (z - qz) * (z - qz);
        if (d < best) {
          best = d;
          bi = i;
          bt = t;
        }
      }
    }
    const p = this._proj;
    p.i = bi;
    p.t = bt;
    p.s = this.cum[bi] + this.segLen[bi] * bt;
    p.tx = this.tx[bi];
    p.tz = this.tz[bi];
    // 左向き法線: 前方 (tx, tz) を 90° 回転
    p.nx = p.tz;
    p.nz = -p.tx;
    p.cx = this.x[bi] + p.tx * this.segLen[bi] * bt;
    p.cz = this.z[bi] + p.tz * this.segLen[bi] * bt;
    p.lat = (x - p.cx) * p.nx + (z - p.cz) * p.nz;
    return p;
  }

  /**
   * project 用の格子。各セグメントを「そのセグメントから reach 以内に入るマス」すべてに登録する。
   * 点から最も近いセグメントまでの距離が reach 以下なら、その点のマスの一覧に必ず含まれる（＝結果は全探索と同じ）。
   */
  _buildGrid() {
    const reach = 26;
    const cell = 40;
    const N = this.n;
    let minX = Infinity;
    let maxX = -Infinity;
    let minZ = Infinity;
    let maxZ = -Infinity;
    for (let i = 0; i < N; i++) {
      minX = Math.min(minX, this.x[i]);
      maxX = Math.max(maxX, this.x[i]);
      minZ = Math.min(minZ, this.z[i]);
      maxZ = Math.max(maxZ, this.z[i]);
    }
    const x0 = minX - reach - cell;
    const z0 = minZ - reach - cell;
    const nx = Math.ceil((maxX + reach + cell - x0) / cell) + 1;
    const nz = Math.ceil((maxZ + reach + cell - z0) / cell) + 1;
    const cells = Array.from({ length: nx * nz }, () => []);
    for (let i = 0; i < N; i++) {
      const k = (i + 1) % N;
      const lx = Math.min(this.x[i], this.x[k]) - reach;
      const hx = Math.max(this.x[i], this.x[k]) + reach;
      const lz = Math.min(this.z[i], this.z[k]) - reach;
      const hz = Math.max(this.z[i], this.z[k]) + reach;
      for (let cz = Math.floor((lz - z0) / cell); cz <= Math.floor((hz - z0) / cell); cz++) {
        for (let cx = Math.floor((lx - x0) / cell); cx <= Math.floor((hx - x0) / cell); cx++) cells[cz * nx + cx].push(i);
      }
    }
    this._grid = { x0, z0, cell, nx, nz, cells, reach };
  }

  /** 弧長 s がトンネルの中か（入口・出口のそれぞれ margin 手前から「中」とみなす） */
  inTunnel(s, margin = 0) {
    const L = this.length;
    s = ((s % L) + L) % L;
    for (const t of this.tunnels) if (s >= t.a - margin && s <= t.b + margin) return true;
    return false;
  }

  /** 弧長 s・横位置 lat の点と、その地点の進行方向 */
  pointAt(s, lat = 0) {
    const L = this.length;
    s = ((s % L) + L) % L;
    let lo = 0;
    let hi = this.n - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (this.cum[mid] <= s) lo = mid;
      else hi = mid - 1;
    }
    const i = lo;
    const t = (s - this.cum[i]) / this.segLen[i];
    const tx = this.tx[i];
    const tz = this.tz[i];
    const cx = this.x[i] + tx * this.segLen[i] * t;
    const cz = this.z[i] + tz * this.segLen[i] * t;
    return { x: cx + tz * lat, z: cz - tx * lat, h: Math.atan2(tx, tz), tx, tz };
  }

  /** チェックポイント k の弧長位置 */
  cpS(k) {
    return (k / this.checkpoints) * this.length;
  }

  /** a - b を -L/2..L/2 に正規化した弧長差 */
  wrapDS(ds) {
    const L = this.length;
    ds = ((ds % L) + L) % L;
    return ds > L / 2 ? ds - L : ds;
  }

  /** アイテムボックスの配置（コース上の 6 か所 × 横 5 列） */
  itemBoxes() {
    const out = [];
    for (const f of [0.1, 0.27, 0.43, 0.6, 0.77, 0.92]) {
      for (const lat of [-8, -4, 0, 4, 8]) {
        const p = this.pointAt(f * this.length, lat);
        out.push({ x: p.x, z: p.z });
      }
    }
    return out;
  }

  /** (x, z) がブーストパッドの上なら true */
  onPad(x, z) {
    const hl = PAD.LENGTH / 2;
    const hw = PAD.WIDTH / 2;
    for (const p of this.pads) {
      const dx = x - p.x;
      const dz = z - p.z;
      if (Math.abs(dx * p.tx + dz * p.tz) <= hl && Math.abs(dx * p.tz - dz * p.tx) <= hw) return true;
    }
    return false;
  }

  /** スタート位置: 前列に人間（0 = ホスト, 1 = ゲスト）、2 列目以降に NPC（2 台ずつ） */
  startPos(index) {
    const row = Math.floor(index / 2);
    const side = index % 2 === 0 ? 1 : -1;
    return this.pointAt(-10 - row * 8, side * 5);
  }

  /** 中心線の範囲（背景の配置などに使う） */
  bounds() {
    let minX = Infinity, maxX = -Infinity, minZ = Infinity, maxZ = -Infinity;
    for (let i = 0; i < this.n; i++) {
      minX = Math.min(minX, this.x[i]);
      maxX = Math.max(maxX, this.x[i]);
      minZ = Math.min(minZ, this.z[i]);
      maxZ = Math.max(maxZ, this.z[i]);
    }
    return { minX, maxX, minZ, maxZ };
  }
}
